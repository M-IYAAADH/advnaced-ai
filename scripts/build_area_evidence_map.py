"""MF-31: evidence map of the 200 m grid (status categories only; no ranking, no counts shading).

Inputs: derived/male_grid_200m.geojson, derived/grid_evidence.csv, derived/grid_blocks.csv,
  derived/male_wards_osm.geojson, OneMap island outline, OSM roads (see paths below).
Outputs: derived/grid_evidence_map.geojson, derived/area_evidence_map.png/.pdf, qgis/male_area_evidence.qgz
NOTE: the .qgz was generated by this script from a hand-written XML template and has NOT yet been
opened in QGIS; open it and check layer paths and styling before relying on it.
Run from the project root: python scripts/build_area_evidence_map.py
"""
import json
import math
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd
from matplotlib.lines import Line2D
from matplotlib.patches import PathPatch, Patch, Polygon
from matplotlib.path import Path as MplPath

RAW = Path("Male_Flood_Data_Starter_Pack")
ISLAND = RAW / "boundary/OneMap_Male_Island.geojson"
ROADS = RAW / "mapping/male_osm_roads.geojson"
OUT = Path("derived")
EXCEPTION = "G333600_461800"  # kept by exception in reports/mf26_blocks_proposal.md

LAT0, LON0 = 4.175, 73.5  # same local metre projection as build_ward_map.py
KX, KY = 111320 * math.cos(math.radians(LAT0)), 110574
INK, SEA = "#2b2b2b", "#eef2f4"
FONT = "Gill Sans"

# status -> (colour, legend label); colours are categories, not an ordered scale
STATUS = {
    "reported_flooding": ("#d95f02", "Reported flooding (stated)"),
    "pumping_only": ("#7fb2d6", "Pumping only (where pumps were deployed)"),
    "designated": ("#8e6bb8", "Designated flood-prone (council list)"),
    "unknown": ("#f4f1ea", "Unknown (no report)"),
}
L_HATCH = "Below proposed land-fraction rule (proposal, not agreed)"
L_RF071 = "Stated only by RF071 (construction confounder, issue E5)"
L_PUMP = "Routine pump site (IGMH, West Park/STO)"


def xy(lon, lat):
    return (lon - LON0) * KX, (lat - LAT0) * KY


def rings(geom):
    polys = [geom["coordinates"]] if geom["type"] == "Polygon" else geom["coordinates"]
    return [p[0] for p in polys]


def build_layer():
    grid = json.loads((OUT / "male_grid_200m.geojson").read_text())
    ev = pd.read_csv(OUT / "grid_evidence.csv", dtype=str, keep_default_na=False).set_index("cell_id")
    bl = pd.read_csv(OUT / "grid_blocks.csv", dtype=str, keep_default_na=False).set_index("cell_id")
    cols = [c for c in ev.columns if c not in ("ward",)]
    for f in grid["features"]:
        cid = f["properties"]["cell_id"]
        f["properties"] = {"cell_id": cid, **ev.loc[cid].to_dict(), "kept_lf025": bl.loc[cid, "kept_lf025"], "block_id": bl.loc[cid, "block_id"]}
    (OUT / "grid_evidence_map.geojson").write_text(json.dumps(grid, ensure_ascii=False))
    return grid


def draw(grid):
    island = [xy(*p) for p in json.loads(ISLAND.read_text())["features"][0]["geometry"]["coordinates"][0]]
    roads = json.loads(ROADS.read_text())["features"]
    wards = json.loads((OUT / "male_wards_osm.geojson").read_text())["features"]

    plt.rcParams["font.family"] = [FONT, "DejaVu Sans"]
    plt.rcParams["hatch.linewidth"] = 0.6
    fig, ax = plt.subplots(figsize=(10, 7.4), dpi=200)
    fig.patch.set_facecolor(SEA)
    ax.set_facecolor(SEA)
    ax.set_aspect("equal")
    ax.axis("off")
    clip = Polygon(island, closed=True, transform=ax.transData)
    ax.add_patch(Polygon(island, closed=True, fc="#faf9f6", ec="none"))

    for f in grid["features"]:
        p = f["properties"]
        pts = [xy(*q) for q in rings(f["geometry"])[0]]
        fc = STATUS[p["status"]][0]
        hatched = p["kept_lf025"] == "no" and p["cell_id"] != EXCEPTION
        rf = p["stated_only_construction_confounded"] == "yes"
        ax.add_patch(Polygon(pts, closed=True, fc=fc, ec="#9a9a9a", lw=0.4, alpha=0.9, zorder=2))
        if hatched:
            ax.add_patch(Polygon(pts, closed=True, fc="none", ec="#555555", hatch="////", lw=0, zorder=3))
        if rf:
            ax.add_patch(Polygon(pts, closed=True, fc="none", ec="#7a1010", lw=2.0, ls=(0, (3, 1.5)), zorder=6))
        if p["routine_pump_site"] == "yes":
            cx = sum(x for x, _ in pts[:4]) / 4
            cy = sum(y for _, y in pts[:4]) / 4
            ax.plot(cx, cy, marker="v", ms=7, mfc=INK, mec="white", mew=0.8, ls="none", zorder=7)

    for f in roads:
        cls = f["properties"]["fclass"]
        if cls in {"footway", "path", "steps"} or f["geometry"]["type"] != "LineString":
            continue
        pts = [xy(*c) for c in f["geometry"]["coordinates"]]
        ln = ax.add_patch(PathPatch(MplPath(pts), fc="none", ec="#8c8c8c", lw=0.4, zorder=4))
        ln.set_clip_path(clip)
    for w in wards:
        for r in rings(w["geometry"]):
            e = ax.add_patch(Polygon([xy(*q) for q in r], closed=True, fc="none", ec="#3a3a3a", lw=0.9, ls="--", zorder=5))
            e.set_clip_path(clip)
    ax.add_patch(Polygon(island, closed=True, fc="none", ec=INK, lw=0.9, zorder=5))

    shift = {"Machchangolhi": (-110, -250)}  # same nudge as build_ward_map.py
    for w in wards:
        name = w["properties"]["ward"]
        big = max((r for r in rings(w["geometry"])), key=lambda r: abs(sum(a[0] * b[1] - b[0] * a[1] for a, b in zip(map(lambda q: xy(*q), r), map(lambda q: xy(*q), r[1:])))))
        P = [xy(*q) for q in big]
        a = cx = cy = 0.0
        for (x0, y0), (x1, y1) in zip(P, P[1:]):
            c = x0 * y1 - x1 * y0
            a, cx, cy = a + c, cx + (x0 + x1) * c, cy + (y0 + y1) * c
        dx, dy = shift.get(name, (0, 0))
        ax.text(cx / (3 * a) + dx, cy / (3 * a) + dy, name.upper(), ha="center", va="center", fontsize=9, color=INK, fontweight="bold", zorder=8,
                bbox=dict(boxstyle="round,pad=0.2", fc="white", ec="none", alpha=0.7))

    xs, ys = zip(*island)
    pad = 160
    xmin, xmax, ymin, ymax = min(xs) - pad, max(xs) + pad, min(ys) - pad * 1.6, max(ys) + pad * 1.5 + 330
    ax.set_xlim(xmin, xmax)
    ax.set_ylim(ymin, ymax)

    x0, y0 = xmin + 40, ymin + 60
    for i, fc in enumerate((INK, "white")):
        ax.add_patch(Polygon([(x0 + i * 250, y0), (x0 + (i + 1) * 250, y0), (x0 + (i + 1) * 250, y0 + 14), (x0 + i * 250, y0 + 14)], fc=fc, ec=INK, lw=0.6))
    for d in (0, 250, 500):
        ax.text(x0 + d, y0 + 30, f"{d}" if d < 500 else "500 m", ha="center", va="bottom", fontsize=7.5, color=INK)
    nx, ny = xmax - 60, ymax - 700
    ax.annotate("", xy=(nx, ny + 90), xytext=(nx, ny), arrowprops=dict(arrowstyle="-|>", color=INK, lw=0.9, mutation_scale=10))
    ax.text(nx, ny + 100, "N", ha="center", va="bottom", fontsize=9, color=INK)

    ax.text(xmin + 40, ymax - 40, "Malé island proper: reported flood evidence by 200 m cell", fontsize=14, color=INK, va="top", fontweight="bold")
    ax.text(xmin + 40, ymax - 150, "Positive-only reports. Unknown means no report, not dry. Not a flood-risk map.", fontsize=9, color="#444444", va="top")
    ax.text(xmax - 40, y0, "© OpenStreetMap contributors (ODbL)   Boundary: OneMap Maldives   Grid and evidence: project derived data",
            ha="right", va="bottom", fontsize=6, color="#6a6a6a")

    handles = [Patch(fc=c, ec="#9a9a9a", label=l) for c, l in STATUS.values()]
    handles += [Patch(fc="white", ec="#555555", hatch="////", label=L_HATCH),
                Patch(fc="none", ec="#7a1010", lw=2, ls="--", label=L_RF071),
                Line2D([], [], marker="v", ms=7, mfc=INK, mec="white", ls="none", label=L_PUMP)]
    leg = ax.legend(handles=handles, loc="upper left", bbox_to_anchor=(1.0, 0.85), fontsize=7.5, frameon=False, title="Cell status", title_fontsize=8.5, alignment="left")
    labels = [t.get_text() for t in leg.get_texts()]
    fig.savefig(OUT / "area_evidence_map.png", bbox_inches="tight", pad_inches=0.1, facecolor=SEA, dpi=200)
    fig.savefig(OUT / "area_evidence_map.pdf", bbox_inches="tight", pad_inches=0.1, facecolor=SEA)
    return labels


def rgba(h, a=255):
    return f"{int(h[1:3], 16)},{int(h[3:5], 16)},{int(h[5:7], 16)},{a}"


def fill_symbol(name, colour, outline="#6a6a6a", ow="0.3", fill=True):
    def prop(k, v):
        return f'<Option name="{k}" type="QString" value="{v}"/>'
    return (f'<symbol name="{name}" type="fill" alpha="1" clip_to_extent="1" force_rhr="0"><data_defined_properties/>'
            f'<layer class="SimpleFill" enabled="1" locked="0" pass="0"><Option type="Map">'
            f'{prop("color", rgba(colour) if fill else "0,0,0,0")}{prop("style", "solid")}{prop("outline_color", rgba(outline))}'
            f'{prop("outline_style", "solid")}{prop("outline_width", ow)}{prop("outline_width_unit", "MM")}</Option></layer></symbol>')


def maplayer(lid, name, path, renderer):
    return (f'<maplayer type="vector" geometry="{"Line" if "roads" in lid else "Polygon"}"><id>{lid}</id><datasource>{path}</datasource>'
            f'<layername>{name}</layername><srs><spatialrefsys><authid>EPSG:4326</authid></spatialrefsys></srs>'
            f'<provider encoding="UTF-8">ogr</provider>{renderer}</maplayer>')


def build_qgz():
    cats = "".join(f'<category value="{k}" label="{l}" symbol="{i}" render="true"/>' for i, (k, (c, l)) in enumerate(STATUS.items()))
    syms = "".join(fill_symbol(str(i), c) for i, (c, l) in enumerate(STATUS.values()))
    grid_r = (f'<renderer-v2 type="categorizedSymbol" attr="status" forceraster="0" symbollevels="0" enableorderby="0">'
              f'<categories>{cats}</categories><symbols>{syms}</symbols></renderer-v2>')
    single = lambda s: f'<renderer-v2 type="singleSymbol" forceraster="0" symbollevels="0" enableorderby="0"><symbols>{s}</symbols></renderer-v2>'
    line = ('<symbol name="0" type="line" alpha="1"><data_defined_properties/><layer class="SimpleLine" enabled="1" locked="0" pass="0">'
            '<Option type="Map"><Option name="line_color" type="QString" value="140,140,140,255"/><Option name="line_width" type="QString" value="0.2"/></Option></layer></symbol>')
    layers = [
        ("grid_evidence_map", "Grid cells by status", "../derived/grid_evidence_map.geojson", grid_r),
        ("male_wards_osm", "Wards (OSM)", "../derived/male_wards_osm.geojson", single(fill_symbol("0", "#000000", "#3a3a3a", "0.5", fill=False))),
        ("male_osm_roads", "Roads (OSM)", "../Male_Flood_Data_Starter_Pack/mapping/male_osm_roads.geojson", single(line)),
        ("OneMap_Male_Island", "Island outline (OneMap)", "../Male_Flood_Data_Starter_Pack/boundary/OneMap_Male_Island.geojson", single(fill_symbol("0", "#000000", "#2b2b2b", "0.5", fill=False))),
    ]
    tree = "".join(f'<layer-tree-layer id="{i}" name="{n}" source="{p}" providerKey="ogr" checked="Qt::Checked" expanded="0"/>' for i, n, p, _ in layers)
    srs = '<spatialrefsys><authid>EPSG:32643</authid></spatialrefsys>'
    xml = (f'<!DOCTYPE qgis PUBLIC \'http://mrcc.com/qgis.dtd\' \'SYSTEM\'><qgis version="3.34.0" projectname="Male area evidence">'
           f'<title>Male area evidence (generated, not yet opened in QGIS)</title><projectCrs>{srs}</projectCrs>'
           f'<layer-tree-group name="">{tree}</layer-tree-group>'
           f'<projectlayers>{"".join(maplayer(i, n, p, r) for i, n, p, r in layers)}</projectlayers></qgis>')
    with zipfile.ZipFile("qgis/male_area_evidence.qgz", "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("male_area_evidence.qgs", xml)
    return [p for _, _, p, _ in layers]


def check(grid, labels, paths):
    base = json.loads((OUT / "male_grid_200m.geojson").read_text())
    ids = [f["properties"]["cell_id"] for f in grid["features"]]
    assert len(ids) == 75 == len(set(ids)) == len(base["features"])
    assert set(ids) == {f["properties"]["cell_id"] for f in base["features"]}
    assert {f["properties"]["status"] for f in grid["features"]} <= set(STATUS)
    assert any("Unknown (no report)" in l for l in labels) and not any("dry" in l.lower().replace("not dry", "") for l in labels)
    assert (OUT / "area_evidence_map.png").stat().st_size > 0 and (OUT / "area_evidence_map.pdf").stat().st_size > 0
    with zipfile.ZipFile("qgis/male_area_evidence.qgz") as z:
        names = z.namelist()
        assert len(names) == 1 and names[0].endswith(".qgs")
        root = ET.fromstring(z.read(names[0]).decode().split("\n", 0)[0].replace(root_doctype(), ""))
    assert root.tag == "qgis"
    for p in paths:
        assert not p.startswith("/") and (Path("qgis") / p).exists(), p
    for ds in root.iter("datasource"):
        assert ds.text in paths


def root_doctype():
    return "<!DOCTYPE qgis PUBLIC 'http://mrcc.com/qgis.dtd' 'SYSTEM'>"


if __name__ == "__main__":
    g = build_layer()
    lab = draw(g)
    pth = build_qgz()
    check(g, lab, pth)
    print("ok", len(g["features"]), "cells")
